#!/usr/bin/env node
/**
 * 广告位的唯一来源 = 飞书「站点台账(人工)YYYY-MM」的两列代码（2026-10-26 起）。
 *
 * 原先还有一张「广告位管理」表（tblPlFjSok72tnA1）存同一批代码 + 同步状态，
 * 等于把台账的东西抄一遍再维护两套状态机——已删除。现在：
 *
 *   人填：广告位1-SocialBar-code（global 位）/ 广告位2-NativeBanner-code（guide 位）
 *   脚本：把代码写进 <site>/lib/adsterra-zones.ts → 部署
 *   状态：不看云表，看**事实**——
 *         · 已注入 = zones 文件里有没有这段代码
 *         · 已上线 = .agent/adsterra-state.json 里记着这次部署成功
 *
 * 台账里没填的栏位**不动**站点已有的 zone（空着不等于要清空，避免误删线上广告）。
 */

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import {
  BASE_TOKEN,
  MANUAL_AD_SLOTS,
  cellScalar,
  lark,
  resolveManualLedgerTable,
  siteDirOf,
} from './month-ledger.mjs';

export const ZONES_REL = path.join('lib', 'adsterra-zones.ts');
export const STATE_REL = path.join('.agent', 'adsterra-state.json');

const HEADER =
  '// AUTO-GENERATED by scripts/adsterra-sync.mjs — do not edit by hand.\n';

/** 生成 `lib/adsterra-zones.ts` 的内容（格式变了就等于所有站要重新部署，别乱动）。 */
export function zonesSource(zones) {
  const fmt = (list) =>
    list.length === 0
      ? '[]'
      : `[\n${list
          .map(
            (z) =>
              `    { name: ${JSON.stringify(z.name)}, html: ${JSON.stringify(z.html)} },`,
          )
          .join('\n')}\n  ]`;
  return `${HEADER}export const ADSTERRA_ZONES = {\n  global: ${fmt(
    zones.global ?? [],
  )},\n  guide: ${fmt(zones.guide ?? [])},\n} as const;\n`;
}

export function zonesPath(repo, site) {
  return path.join(repo, site, ZONES_REL);
}

/** 读站点当前的 zones；文件不存在返回 null。 */
export function readZonesSource(repo, site) {
  const p = zonesPath(repo, site);
  return fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
}

/** 解析生成的 zones 文件；解析不出结构时返回空数组（宁可少认，不要认错）。 */
export function parseZones(src) {
  const out = { global: [], guide: [] };
  if (!src) return out;
  for (const slot of ['global', 'guide']) {
    const start = src.indexOf(`  ${slot}: [`);
    if (start === -1) continue;
    const end = src.indexOf('\n  ],', start);
    if (end === -1) continue;
    const body = src.slice(start, end);
    const re = /^ {4}\{ name: (.+?), html: (.+?) \},$/gm;
    let m;
    while ((m = re.exec(body))) {
      try {
        out[slot].push({ name: JSON.parse(m[1]), html: JSON.parse(m[2]) });
      } catch {
        /* 手工改坏的行跳过 */
      }
    }
  }
  return out;
}

/**
 * 把台账里的代码合进站点现有的 zones。
 * 只覆盖「台账填了的」栏位，其余原样保留——台账空着不代表要下线广告。
 */
export function mergeZones(existing, codes, site) {
  const zones = {
    global: [...(existing?.global ?? [])],
    guide: [...(existing?.guide ?? [])],
  };
  for (const { slot, format } of MANUAL_AD_SLOTS) {
    const code = (codes[slot] || '').trim();
    if (!code) continue;
    const prev = zones[slot];
    // 一个位只放一份代码：沿用原来的名字，没有就用 `<site>-<slot>`
    const name = prev[0]?.name || `${site}-${slot}`;
    zones[slot] = [{ name, html: code, format }];
  }
  return zones;
}

export const codeHash = (code) =>
  crypto.createHash('sha1').update(code.trim()).digest('hex').slice(0, 12);

/* ─── 上线状态（本地事实，不依赖云表） ────────────────────────────── */

export function readState(repo) {
  const p = path.join(repo, STATE_REL);
  if (!fs.existsSync(p)) return {};
  try {
    return JSON.parse(fs.readFileSync(p, 'utf8'));
  } catch {
    return {};
  }
}

export function writeState(repo, state) {
  const p = path.join(repo, STATE_REL);
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, `${JSON.stringify(state, null, 2)}\n`);
}

/** 记下这个站的这些 zone 已经部署上线（按代码 hash 认，代码一换 hash 就对不上）。 */
export function markLive(repo, site, zones, at = new Date().toISOString()) {
  if (!zones) return;
  const state = readState(repo);
  const entry = state[site] ?? {};
  for (const slot of ['global', 'guide']) {
    for (const z of zones[slot] ?? []) {
      if (!z?.html) continue;
      entry[slot] = { hash: codeHash(z.html), deployedAt: at };
    }
  }
  state[site] = entry;
  writeState(repo, state);
}

/**
 * 这个栏位的代码是不是「已注入 + 已上线」。
 * 注入看站点文件，上线看 state 里的 hash 是否还等于当前代码。
 */
export function slotLive(repo, site, slot, code, { zones, state } = {}) {
  const want = codeHash(code);
  const zs = zones ?? parseZones(readZonesSource(repo, site));
  const st = state ?? readState(repo);
  const injected = (zs[slot] ?? []).some((z) => z?.html && codeHash(z.html) === want);
  const deployed = st[site]?.[slot]?.hash === want;
  return { injected, deployed, live: injected && deployed };
}

/* ─── 一次性重建 state（从部署日志反推，2026-10-26 建 state 时用） ── */

const git = (repo, args) => {
  try {
    return execFileSync('git', args, {
      cwd: repo,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch {
    return '';
  }
};

/**
 * `git show <commit>:<path>` 的 path 相对**仓库根**，而这里传进来的是相对 `repo` 的。
 * 仓库根可能在上层目录（monorepo），先问 git 自己在哪个子目录里。
 */
function gitPath(repo, rel) {
  const prefix = git(repo, ['rev-parse', '--show-prefix']);
  return `${prefix}${rel}`;
}

/** 部署日志里最后一次成功部署：site → { ts, commit }。 */
function lastDeploys(repo) {
  const logPath = path.join(repo, '.agent', 'deploy-log.jsonl');
  const out = new Map();
  if (!fs.existsSync(logPath)) return out;
  for (const line of fs.readFileSync(logPath, 'utf8').split('\n')) {
    if (!line.trim()) continue;
    let row;
    try {
      row = JSON.parse(line);
    } catch {
      continue;
    }
    if (row.status !== 'ok' || !row.site || !row.commit) continue;
    const ts = Date.parse(row.ts);
    if (!Number.isFinite(ts)) continue;
    const prev = out.get(row.site);
    if (!prev || ts > prev.ts) out.set(row.site, { ts, commit: row.commit });
  }
  return out;
}

/**
 * 从 `.agent/deploy-log.jsonl` 反推「这些代码其实早就部署上线了」。
 *
 * 部署日志记了当时的 commit，所以能精确回看**线上那一版**的广告文件：
 *   1. `git show <commit>:<site>/lib/adsterra-zones.ts` 存在，且和当前文件逐字节相同
 *   2. 那一版 layout.tsx / GuideLayout.tsx 里已经有 ADSTERRA 注入标记
 * 两条都成立 = 线上跑的就是现在这份广告代码。只补 state 里没有的站。
 *
 * 用途：state 是 2026-10-26 新引入的，此前 46 站的广告早已上线；
 * 不做这一步，首轮 `--status-only` 会把所有站误标成「待回填」。
 */
export function seedLiveFromDeployLog(repo, { apply = false } = {}) {
  const deploys = lastDeploys(repo);
  const state = readState(repo);
  const seeded = [];
  const skipped = [];
  const sites = fs
    .readdirSync(repo, { withFileTypes: true })
    .filter((d) => d.isDirectory() && d.name.endsWith('wiki'))
    .map((d) => d.name)
    .sort();

  for (const site of sites) {
    const current = readZonesSource(repo, site);
    const zones = parseZones(current);
    if (!zones.global.length && !zones.guide.length) continue;
    if (state[site]) {
      skipped.push(`${site}（已有记录）`);
      continue;
    }
    const deployed = deploys.get(site);
    if (!deployed) {
      skipped.push(`${site}（部署日志里没有成功记录）`);
      continue;
    }
    const zonesAtDeploy = git(repo, [
      'show',
      `${deployed.commit}:${gitPath(repo, `${site}/${ZONES_REL}`)}`,
    ]);
    if (!zonesAtDeploy) {
      skipped.push(`${site}（那一版部署时还没有 zones 文件）`);
      continue;
    }
    if (zonesAtDeploy !== current.trimEnd()) {
      skipped.push(`${site}（zones 改过，还没部署）`);
      continue;
    }
    const markersOk = ['app/layout.tsx', 'components/GuideLayout.tsx'].every((rel) => {
      const atDeploy = git(repo, [
        'show',
        `${deployed.commit}:${gitPath(repo, `${site}/${rel}`)}`,
      ]);
      return (
        atDeploy.includes('ADSTERRA:') &&
        fs.readFileSync(path.join(repo, site, rel), 'utf8').includes('ADSTERRA:')
      );
    });
    if (!markersOk) {
      skipped.push(`${site}（那一版没有注入标记，或当前文件已改）`);
      continue;
    }
    seeded.push(site);
    if (apply) markLive(repo, site, zones, new Date(deployed.ts).toISOString());
  }

  return { seeded, skipped };
}


/* ─── 读台账 → 广告位行 ───────────────────────────────────────────── */

function readAll(tableId, cwd) {
  const rows = [];
  let offset = 0;
  for (;;) {
    const data = lark(
      [
        'base',
        '+record-list',
        '--base-token',
        BASE_TOKEN,
        '--table-id',
        tableId,
        '--format',
        'json',
        '--limit',
        '200',
        '--offset',
        String(offset),
      ],
      { cwd },
    );
    const fields = data.fields ?? [];
    (data.data ?? []).forEach((cells, i) => {
      const row = { __record: data.record_id_list?.[i] };
      fields.forEach((name, c) => {
        const v = cellScalar(cells[c]);
        row[name] = v == null ? '' : String(v);
      });
      rows.push(row);
    });
    if (!data.has_more || (data.data ?? []).length === 0) break;
    offset += data.data.length;
  }
  return rows;
}

/**
 * 台账 → `adsterra-sync` 认的行形状。
 * 一个填了代码的栏位 = 一行；栏位 → 广告位类型由 MANUAL_AD_SLOTS 决定。
 */
export function rowsFromManualLedger({
  repo,
  table = null,
  month = null,
  cwd = repo,
  onlySite = null,
} = {}) {
  const ledger = resolveManualLedgerTable({ table, month, cwd });
  const knownDirs = new Set(
    fs
      .readdirSync(repo, { withFileTypes: true })
      .filter((d) => d.isDirectory() && d.name.endsWith('wiki'))
      .map((d) => d.name),
  );

  const rows = [];
  let line = 1;
  for (const r of readAll(ledger.id, cwd)) {
    const site = siteDirOf(r['站点'], knownDirs);
    if (!site) continue;
    if (onlySite && site !== onlySite) continue;
    const domain = String(r['站点'] || '').trim().toLowerCase();
    for (const { field, slot, format } of MANUAL_AD_SLOTS) {
      const code = (r[field] || '').trim();
      if (!code) continue;
      rows.push({
        site_dir: site,
        domain,
        slot,
        format,
        placement_name: `${site}-${slot}`,
        code,
        status: '',
        sync_status: '',
        __record: r.__record,
        __line: ++line,
      });
    }
  }
  return { ledger, rows };
}
